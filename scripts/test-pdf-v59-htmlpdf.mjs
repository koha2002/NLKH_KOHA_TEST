import fs from "node:fs";
const idx=fs.readFileSync("public/tool-modules/pdf/index.html","utf8");
const ui=fs.readFileSync("public/tool-modules/pdf/pdf-ui-v50.js","utf8");
const ok=(v,m)=>{if(!v){console.error("FAIL:",m);process.exitCode=1}else console.log("PASS:",m)};
const values=[...idx.matchAll(/<option value="([^"]+)"/g)].map(x=>x[1]);
ok(values.length===31,"Exactly 31 static tool options");
ok(new Set(values).size===31,"No duplicate tool IDs");
ok(values.includes("htmlpdf"),"Web/URL -> PDF registered");
ok(idx.includes("pdf-ui-v50.js?v=59"),"V59 cache version");
ok(/htmlpdf:\{offline:false,online:true\}/.test(ui),"Web -> PDF Online-only");
ok(ui.includes("cloud_file:url"),"Official cloud_file upload field used");
ok(ui.includes("'Content-Type':'application/json;charset=UTF-8'"),"Cloud URL upload uses JSON like official JS SDK");
ok(ui.includes("uploadCloudUrlV59"),"Dedicated URL upload workflow");
ok(ui.includes("if(k!=='htmlpdf'&&!list.length)"),"Web -> PDF does not require local file");
ok(ui.includes("box.classList.toggle('hidden',urlOnly)"),"Local upload box hidden for URL tool");
ok(ui.includes("validHtmlPdfUrlV59"),"HTTP/HTTPS URL validation present");
ok(ui.includes("V59 uses Basic Web → PDF only"),"UI explicitly limits scope to verified Basic flow");
ok(!ui.includes("htmlPdfPageSize")&&!ui.includes("htmlPdfOrientation")&&!ui.includes("htmlPdfSinglePage"),"No unverified advanced HTML-PDF settings invented");
ok(!values.includes("pdfword")&&!values.includes("pdfexcel")&&!values.includes("pdfpowerpoint"),"No invented PDF-to-Office tools");
if(process.exitCode)process.exit(process.exitCode);
console.log("PDF V59 HTMLPDF scoped checks passed.");
