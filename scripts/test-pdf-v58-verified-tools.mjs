import fs from "node:fs";
const idx=fs.readFileSync("public/tool-modules/pdf/index.html","utf8");
const ui=fs.readFileSync("public/tool-modules/pdf/pdf-ui-v50.js","utf8");
const ok=(v,m)=>{if(!v){console.error("FAIL:",m);process.exitCode=1}else console.log("PASS:",m)};
const values=[...idx.matchAll(/<option value="([^"]+)"/g)].map(x=>x[1]);
ok(values.length===30,"Exactly 30 static tool options");
ok(new Set(values).size===30,"No duplicate tool IDs");
ok(values.includes("validatepdfa"),"Validate PDF/A registered");
ok(values.includes("upscaleimage"),"Upscale Image registered");
ok(values.includes("repairimage"),"Repair Image registered");
ok(!values.includes("pdfword")&&!values.includes("pdfexcel")&&!values.includes("pdfpowerpoint"),"No invented PDF-to-Office REST tools");
ok(idx.includes("pdf-ui-v50.js?v=58"),"V58 cache version");
ok(/validatepdfa:\{offline:false,online:true\}/.test(ui),"Validate PDF/A Online-only");
ok(/upscaleimage:\{offline:false,online:true\}/.test(ui),"Upscale Image Online-only");
ok(/repairimage:\{offline:false,online:true\}/.test(ui),"Repair Image Online-only");
ok(ui.includes("body.multiplier=Number"),"Upscale multiplier sent");
ok(ui.includes("body.allow_downgrade=false"),"PDF/A validation is strict by default");
ok(ui.includes("result.validations"),"Validate PDF/A consumes validation response");
ok(ui.includes("it does not create a new PDF"),"Validation UI explains no downloadable file");
ok(ui.includes("The official API supports 2× or 4× only"),"Upscale UI reflects official limits");
ok(ui.includes("No fake settings are shown"),"Repair Image has no fake settings");
if(process.exitCode)process.exit(process.exitCode);
console.log("PDF V58 verified-tools scoped checks passed.");
