import fs from 'node:fs';
const idx=fs.readFileSync('public/tool-modules/pdf/index.html','utf8');
const ui=fs.readFileSync('public/tool-modules/pdf/pdf-ui-v50.js','utf8');
const tile=fs.readFileSync('public/tool-modules/pdf/tile-pages-v62.js','utf8');
const ok=(v,m)=>{if(!v){console.error('FAIL:',m);process.exitCode=1}else console.log('PASS:',m)};
const values=[...idx.matchAll(/<option value="([^"]+)"/g)].map(x=>x[1]);
ok(values.length===32,'Exactly 32 static tool options');
ok(new Set(values).size===32,'No duplicate tool IDs');
ok(values.includes('tilepages'),'Tile PDF Pages registered');
ok(idx.indexOf('value="split"')<idx.indexOf('value="tilepages"')&&idx.indexOf('value="tilepages"')<idx.indexOf('value="splitsmart"'),'Tile Pages placed beside Split / Smart Split');
ok(/tilepages:\{offline:true,online:false\}/.test(ui),'Tile Pages is Offline-only');
ok(/PROTECTED_UI=new Set\(\[[^\]]*'tilepages'/.test(ui),'Central UI delegates Tile Pages to specialized module');
ok(ui.includes("vi:'Chia nhỏ trang PDF'")&&ui.includes("en:'Tile PDF Pages'"),'Bilingual finder metadata');
ok(idx.includes('tile-pages-v62.css?v=62')&&idx.includes('tile-pages-v62.js?v=62'),'V62 assets loaded');
ok(idx.indexOf('tile-pages-v62.js?v=62')<idx.indexOf('offline-v2.js?v=60'),'Tile interceptor loads before generic Offline runtime');
ok(tile.includes("['A0',2383.94,3370.39]")&&tile.includes("['A10',73.70,104.88]"),'ISO A0-A10 geometry included');
ok(tile.includes("st.target==='down1'")&&tile.includes("st.target==='down2'")&&tile.includes("st.target==='down3'"),'2 / 4 / 8-sheet ISO presets');
ok(tile.includes("if(parts==='6')"),'6-part layout supported');
ok(tile.includes("'custom'"),'Custom rows x columns supported');
ok(tile.includes('setMediaBox')&&tile.includes('setCropBox'),'Output uses PDF page boxes');
ok(!tile.includes('getContext(')&&!tile.includes('toDataURL('),'Tile engine does not rasterize pages');
ok(tile.includes('MAX=500'),'Local output safety limit exists');
ok(tile.includes('A4 → 2×A5')&&tile.includes('A1 → 4×A3'),'Paper relationship examples are explicit');
if(process.exitCode)process.exit(process.exitCode);
console.log('PDF V62 Tile Pages scoped checks passed.');
